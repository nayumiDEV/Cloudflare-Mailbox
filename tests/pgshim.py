"""A stand-in for psycopg3 that executes the generated SQL on real SQLite.

Purpose: exercise the actual PostgreSQL code path in app.py/db.py without a
PostgreSQL server. The SQL PostgreSQL would receive is already validated as
legal by pglast; this shim goes one step further and runs it, so behaviour that
static analysis cannot see is caught too -- `lastrowid` availability, BLOB
round-trips, dict-row access, foreign-key cascades, upserts.

Only the constructs the app actually emits need translating:

===========================  ==========================================
PostgreSQL                   shim
===========================  ==========================================
``%s`` parameter markers     ``?``
identity primary key         ``INTEGER PRIMARY KEY AUTOINCREMENT``
``smallint`` / ``bytea``     accepted by SQLite as-is
``tsvector`` generated col   removed from DDL
``USING GIN (search_vector)``index dropped
``search_vector @@ tsquery``  widened to a LIKE so recall still matches
``ILIKE``                    ``LIKE`` (SQLite LIKE is case-insensitive,
                             which is what ILIKE asks for)
===========================  ==========================================

Anything else is passed through, so an unhandled PostgreSQL construct shows up
as a SQLite error rather than being silently papered over.
"""

from __future__ import annotations

import re
import sqlite3
import sys
import types

_MARKER = re.compile(r"(%s)")
# Consume the column's own leading comma and trailing whitespace too, otherwise
# removing the column leaves `..., )` and the table fails to parse.
_TSVECTOR_DDL = re.compile(
    r",?\s*search_vector\s+tsvector\s+GENERATED ALWAYS AS \(.*?\)\s*STORED\s*,?",
    re.S | re.I,
)
# The statement has already been split on ';', so there is no terminator to
# anchor to.
_GIN_INDEX = re.compile(r"CREATE INDEX[^;]*USING GIN[^;]*", re.S | re.I)
_IDENTITY = re.compile(
    r"\binteger\s+GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY\b",
    re.I,
)
# Matches the marker in either form: this substitution runs before `%s` has
# been rewritten to `?`.
_TSQUERY = re.compile(
    r"(\w+)\.search_vector\s*@@\s*websearch_to_tsquery\(\s*'simple'\s*,\s*(?:\?|%s)\s*\)",
    re.I,
)


def to_sqlite(sql: str) -> str:
    sql = _TSVECTOR_DDL.sub("", sql)
    sql = _GIN_INDEX.sub("", sql)
    sql = _IDENTITY.sub("INTEGER PRIMARY KEY AUTOINCREMENT", sql)
    # Must yield exactly one placeholder: the original tsquery match consumes
    # one parameter, so widening it must not change the binding count.
    sql = _TSQUERY.sub(r"\1.subject LIKE ?", sql)
    sql = re.sub(r"\bILIKE\b", "LIKE", sql, flags=re.I)
    # Convert markers only outside string literals.
    out, i, n = [], 0, len(sql)
    while i < n:
        ch = sql[i]
        if ch in "\"'":
            quote = ch
            out.append(ch)
            i += 1
            while i < n:
                out.append(sql[i])
                if sql[i] == quote:
                    i += 1
                    break
                i += 1
            continue
        if sql.startswith("%s", i):
            out.append("?")
            i += 2
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def dict_row_factory(cursor, row):
    return {d[0]: row[idx] for idx, d in enumerate(cursor.description)}


class FakeCursor:
    def __init__(self, conn: "FakeConnection", row_factory=None):
        self._conn = conn
        self._cur = conn._raw.cursor()
        self._row_factory = row_factory
        self._rows = None
        self.rowcount = -1
        self.lastrowid = None
        self._sql = None

    def execute(self, sql: str, params=None) -> "FakeCursor":
        self._sql = to_sqlite(sql)
        self._rows = None
        self._emit = dict_row_factory
        bound = list(params) if params else []

        # SQLite has no information_schema; answer the introspection query
        # app.py uses to discover existing columns.
        if "information_schema.columns" in self._sql:
            table = bound[0]
            self._cur.execute(f"PRAGMA table_info({table})")
            self._rows = [{"column_name": r[1]} for r in self._cur.fetchall()]
            self.rowcount = len(self._rows)
            return self

        try:
            self._cur.execute(self._sql, bound)
        except sqlite3.Error as exc:
            raise sqlite3.Error(
                f"{exc}\n--- shimmed SQL ---\n{self._sql}"
            ) from None
        self.rowcount = self._cur.rowcount
        self.lastrowid = self._cur.lastrowid
        return self

    def _load(self):
        if self._rows is None:
            raw = self._cur.fetchall()
            if self._row_factory is dict_row_factory:
                self._rows = [dict_row_factory(self._cur, r) for r in raw]
            else:
                self._rows = raw
        return self._rows

    def fetchone(self):
        rows = self._load()
        return rows[0] if rows else None

    def fetchall(self):
        rows = self._load()
        self._rows = []
        return rows

    def fetchmany(self, size=None):
        return self._load()[: size or 1]

    def __iter__(self):
        return iter(self._load())

    def close(self):
        self._cur.close()


class FakeConnection:
    def __init__(self, path: str, **_kwargs):
        self._raw = sqlite3.connect(path, timeout=30)
        self._raw.row_factory = sqlite3.Row
        self._raw.execute("PRAGMA foreign_keys = ON")
        self.closed = False

    def cursor(self, row_factory=None):
        return FakeCursor(self, row_factory)

    def execute(self, sql, params=None):
        return self.cursor().execute(sql, params)

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self.closed = True
        self._raw.close()


def install(path: str) -> None:
    """Register the shim as `psycopg` so `import psycopg` resolves to it."""
    psycopg = types.ModuleType("psycopg")
    psycopg.__version__ = "3.3.4-shim"
    psycopg.connect = lambda dsn=None, **kw: FakeConnection(path, **kw)
    psycopg.OperationalError = sqlite3.OperationalError
    psycopg.Error = sqlite3.Error

    rows_mod = types.ModuleType("psycopg.rows")
    rows_mod.dict_row = dict_row_factory
    rows_mod.tuple_row = None

    psycopg.rows = rows_mod
    sys.modules["psycopg"] = psycopg
    sys.modules["psycopg.rows"] = rows_mod
